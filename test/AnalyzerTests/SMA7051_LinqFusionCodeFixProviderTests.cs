using Microsoft.VisualStudio.TestTools.UnitTesting;
using SatorImaging.MeticulousAnalyzer.Analysis.Analyzers;
using SatorImaging.MeticulousAnalyzer.CodeFixes.Providers;
using System.Threading.Tasks;

namespace SatorImaging.MeticulousAnalyzer.Tests.AnalyzerTests
{
    using VerifyCS = SatorImaging.MeticulousAnalyzer.Tests.CSharpCodeFixVerifier<LinqFusionAnalyzer, LinqFusionCodeFixProvider>;

    [TestClass]
    public class SMA7051_LinqFusionCodeFixProviderTests
    {
        [TestMethod]
        public async Task SMA7051_CodeFix_WhereAny()
        {
            var source = @"
using System.Collections.Generic;
using System.Linq;

public class C
{
    public bool M(IEnumerable<int> items)
        => {|#0:items.Where(x => x > 0).Any()|};
}
";
            var fixedSource = @"
using System.Collections.Generic;
using System.Linq;

public class C
{
    public bool M(IEnumerable<int> items)
        => items.Fused_Where_Any(x => x > 0);
}
";
            var fusion = @"/*

# Generated by SatorImaging.MeticulousAnalyzer

This file contains fused LINQ operations used by SMA7051.

*/

#nullable enable
internal static partial class LinqFusion
{
    public static bool Fused_Where_Any<TSource>(this global::System.Collections.Generic.IEnumerable<TSource> source, global::System.Func<TSource, bool> predicate)
    {
        foreach (var item in source)
        {
            if (predicate(item))
            {
                return true;
            }
        }
        return false;
    }
}
";
            var test = new VerifyCS.Test
            {
                TestState =
                {
                    Sources = { ("Test0.cs", source) },
                    ExpectedDiagnostics =
                    {
                        VerifyCS.Diagnostic(LinqFusionAnalyzer.RuleId_LinqFusion)
                            .WithLocation(markupKey: 0)
                    }
                },
                FixedState =
                {
                    Sources =
                    {
                        ("Test0.cs", fixedSource),
                        ("LinqFusion.cs", fusion)
                    }
                }
            };
            CSharpVerifierHelper.SetAssemblyName(test, "Application");
            await test.RunAsync();
        }
    }
}
