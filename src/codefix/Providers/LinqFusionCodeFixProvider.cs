using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.CodeFixes;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SatorImaging.MeticulousAnalyzer.Analysis.Analyzers;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Composition;
using System.IO;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace SatorImaging.MeticulousAnalyzer.CodeFixes.Providers
{
    [ExportCodeFixProvider(LanguageNames.CSharp, Name = nameof(LinqFusionCodeFixProvider)), Shared]
    public sealed class LinqFusionCodeFixProvider : CodeFixProvider
    {
        private const string FusionFileHeader =
@"/*

# Generated by SatorImaging.MeticulousAnalyzer

This file contains fused LINQ operations used by SMA7051.

*/

#nullable enable
";

        public sealed override ImmutableArray<string> FixableDiagnosticIds =>
            ImmutableArray.Create(LinqFusionAnalyzer.RuleId_LinqFusion);

        public sealed override FixAllProvider GetFixAllProvider() =>
            WellKnownFixAllProviders.BatchFixer;

        public sealed override async Task RegisterCodeFixesAsync(CodeFixContext context)
        {
            var root = await context.Document.GetSyntaxRootAsync(context.CancellationToken).ConfigureAwait(false);
            if (root == null) return;

            foreach (var diagnostic in context.Diagnostics)
            {
                context.RegisterCodeFix(
                    CodeAction.Create(
                        "Generate and use LINQ fusion method",
                        cancellationToken => ApplyAsync(context.Document, diagnostic, cancellationToken),
                        LinqFusionAnalyzer.RuleId_LinqFusion),
                    diagnostic);
            }
        }

        private static async Task<Solution> ApplyAsync(
            Document document,
            Diagnostic diagnostic,
            CancellationToken cancellationToken)
        {
            var solution = document.Project.Solution;
            var root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
            var semanticModel = await document.GetSemanticModelAsync(cancellationToken).ConfigureAwait(false);
            if (root == null || semanticModel == null) return solution;

            var node = root.FindNode(diagnostic.Location.SourceSpan, getInnermostNodeForTie: true);
            var outerInvocation = node.FirstAncestorOrSelf<InvocationExpressionSyntax>();
            if (outerInvocation == null) return solution;

            if (semanticModel.GetSymbolInfo(outerInvocation, cancellationToken).Symbol is not IMethodSymbol outerMethod
                || outerInvocation.Expression is not MemberAccessExpressionSyntax outerAccess
                || outerAccess.Expression is not InvocationExpressionSyntax innerInvocation
                || semanticModel.GetSymbolInfo(innerInvocation, cancellationToken).Symbol is not IMethodSymbol innerMethod)
            {
                return solution;
            }

            innerMethod = (innerMethod.ReducedFrom ?? innerMethod).ConstructedFrom;
            outerMethod = (outerMethod.ReducedFrom ?? outerMethod).ConstructedFrom;

            var innerName = innerMethod.Name;
            var outerName = outerMethod.Name;
            if (!TryGetFusionName(innerName, outerName, out var fusionName))
            {
                return solution;
            }

            var hasTerminalPredicate = outerInvocation.ArgumentList.Arguments.Count > 0;
            var hasIndexedSelect = innerName == "Select"
                && innerMethod.Parameters.Length >= 3;
            var methodText = LinqFusionCodeGenerator.GenerateMethod(
                innerName,
                outerName,
                hasIndexedSelect,
                hasTerminalPredicate,
                fusionName);

            var callText = await document.GetTextAsync(cancellationToken).ConfigureAwait(false);
            var receiver = innerInvocation.Expression is MemberAccessExpressionSyntax innerAccess
                ? innerAccess.Expression
                : null;
            if (receiver == null) return solution;

            var arguments = new StringBuilder();
            AppendArguments(arguments, innerInvocation.ArgumentList);
            AppendArguments(arguments, outerInvocation.ArgumentList);

            var replacement = receiver.WithoutTrivia().ToFullString()
                + "."
                + fusionName;

            if (innerName == "OfType")
            {
                var ofTypeMethod = (innerMethod.ReducedFrom ?? innerMethod);
                if (ofTypeMethod.TypeArguments.Length > 0)
                {
                    replacement += "<"
                        + ofTypeMethod.TypeArguments[0].ToMinimalDisplayString(semanticModel, outerInvocation.SpanStart)
                        + ">";
                }
            }

            replacement += "(";
            replacement += arguments.ToString();
            replacement += ")";

            callText = callText.WithChanges(new TextChange(outerInvocation.Span, replacement));
            solution = solution.WithDocumentText(document.Id, callText);

            var namespaceName = LinqCodeFixHelper.GetTopLevelNamespaceName(document.Project.DefaultNamespace ?? string.Empty);
            if (string.IsNullOrEmpty(namespaceName))
            {
                namespaceName = LinqCodeFixHelper.GetTopLevelNamespaceName(root);
            }

            var fileName = string.IsNullOrEmpty(namespaceName)
                ? "LinqFusion.cs"
                : "LinqFusion." + namespaceName + ".cs";
            var project = solution.GetProject(document.Project.Id)!;
            var fusionDocument = LinqCodeFixHelper.FindDocument(project, fileName);
            if (fusionDocument == null)
            {
                var filePath = project.FilePath == null
                    ? null
                    : Path.Combine(Path.GetDirectoryName(project.FilePath)!, fileName);
                var source = LinqCodeFixHelper.GenerateEmptyFile(FusionFileHeader, "LinqFusion", namespaceName);
                var documentId = DocumentId.CreateNewId(project.Id, fileName);
                solution = solution.AddDocument(
                    documentId,
                    fileName,
                    Microsoft.CodeAnalysis.Text.SourceText.From(source),
                    filePath: filePath);
                fusionDocument = solution.GetDocument(documentId)!;
            }

            var fusionRoot = await fusionDocument.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
            if (fusionRoot == null) return solution;

            var fusionClass = LinqCodeFixHelper.FindClass(fusionRoot, "LinqFusion");
            if (fusionClass == null) return solution;

            foreach (var member in fusionClass.Members)
            {
                if (member is MethodDeclarationSyntax existing
                    && existing.Identifier.ValueText == fusionName
                    && existing.ParameterList.Parameters.Count == CountParameters(innerName, hasTerminalPredicate))
                {
                    return solution;
                }
            }

            var fusionText = await fusionDocument.GetTextAsync(cancellationToken).ConfigureAwait(false);
            var closeBrace = fusionClass.CloseBraceToken;
            var closeBraceLine = fusionText.Lines.GetLineFromPosition(closeBrace.SpanStart);
            var insertionSpan = TextSpan.FromBounds(closeBraceLine.Start, closeBrace.SpanStart);
            var members = fusionClass.Members;
            var insertion = (members.Count == 0 ? string.Empty : "\n")
                + IndentMethod(methodText, "    ")
                + "\n";

            return solution.WithDocumentText(
                fusionDocument.Id,
                fusionText.WithChanges(new TextChange(insertionSpan, insertion)));
        }

        private static string IndentMethod(string methodText, string indentation)
        {
            var lines = methodText.Split('\n');
            var result = new StringBuilder();
            for (int i = 0, count = lines.Length; i < count; i++)
            {
                if (i > 0) result.Append('\n');
                result.Append(indentation);
                result.Append(lines[i]);
            }
            return result.ToString();
        }

        private static bool TryGetFusionName(string innerName, string outerName, out string fusionName)
        {
            fusionName = "Fused_" + innerName + "_" + outerName;
            return innerName is "Where" or "OfType" or "Select"
                && outerName is "Any" or "First" or "FirstOrDefault" or "Last"
                    or "LastOrDefault" or "Single" or "SingleOrDefault" or "All";
        }

        private static void AppendArguments(StringBuilder arguments, ArgumentListSyntax argumentList)
        {
            for (int i = 0, count = argumentList.Arguments.Count; i < count; i++)
            {
                if (arguments.Length > 0)
                {
                    arguments.Append(", ");
                }
                arguments.Append(argumentList.Arguments[i].ToString());
            }
        }

        private static int CountParameters(string innerName, bool hasTerminalPredicate)
        {
            var count = 1;
            if (innerName is "Where" or "Select")
            {
                count++;
            }
            if (hasTerminalPredicate)
            {
                count++;
            }
            return count;
        }
    }
}
