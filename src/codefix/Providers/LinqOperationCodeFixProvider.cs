        // Microsoft.CodeAnalysis.CSharp 3.8.0 has no named SyntaxKind for file-scoped namespaces.
        private const int FileScopedNamespaceDeclarationRawKind = 8845;

        // DO NO use the auto-generated tag. it will disable analyzer and formatter.
        public const string GeneratedFileHeader =
@"/*

# Generated by SatorImaging.MeticulousAnalyzer

Note that this file is designed to avoid the boxing of value type collections.
Almost all linq operations are optimized for well-known linq combinations
based on the concrete type of IEnumerable returned by linq methods.
Rewriting will change the return type and optimization will be skipped.

When rewriting by hand, should consult the reference source first:
- https://github.com/dotnet/runtime/tree/main/src/libraries/System.Linq/src/System/Linq
- https://github.com/microsoft/referencesource/blob/4.6.2/System.Core/System/Linq/Enumerable.cs

*/

#nullable enable
#pragma warning disable IDE0001 // Simplify name
";

